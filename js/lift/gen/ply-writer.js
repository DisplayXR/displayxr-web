// ply-writer.js — turn lift-gen's two image-aligned layers into Gaussians and serialise them as a
// standard binary 3DGS PLY. Runs as a module Worker (see the bottom of the file) AND imports
// cleanly in Node / the main thread, so the same code is unit-tested and used as a fallback.
//
// EXPERIMENTAL, internal to ./lift-gen.js.
//
// COORDINATES — OpenCV camera frame, metres: +x right, +y DOWN, +z forward (away from the
// camera), the capture camera at the origin, principal point at the image centre. That is the
// frame SHARP, the gallery's `.sog` camera block and `addSplat`'s `flipY` (a 180° turn about X
// into three.js's y-up / −z-forward) all assume. See docs/lift-gen.md.
//
// PLY layout (17 float32 per vertex, little endian) — the 3DGS field names, SH degree 0 only:
//   x y z  nx ny nz(=0)  f_dc_0..2  opacity(logit)  scale_0..2(log σ)  rot_0..3 (quat w,x,y,z)

export const PLY_PROPS = [
  'x', 'y', 'z', 'nx', 'ny', 'nz',
  'f_dc_0', 'f_dc_1', 'f_dc_2',
  'opacity',
  'scale_0', 'scale_1', 'scale_2',
  'rot_0', 'rot_1', 'rot_2', 'rot_3',
];
const NP = PLY_PROPS.length;
/** SH band-0 constant: f_dc = (c − 0.5) / C0. */
export const SH_C0 = 0.28209479177387814;
/** A layer-1 texel with this disparity or less is "no hidden layer here". */
export const NO_LAYER = -100;

export function plyHeader(count, comment = 'generated by @displayxr/inline3d lift-gen') {
  return (
    'ply\nformat binary_little_endian 1.0\n' +
    `comment ${comment}\n` +
    `element vertex ${count}\n` +
    PLY_PROPS.map((p) => `property float ${p}\n`).join('') +
    'end_header\n'
  );
}

const logit = (a) => Math.log(a / (1 - a));

/**
 * Emit both layers as Gaussians and write the PLY.
 *
 * @param {object} p
 * @param {number} p.W @param {number} p.H          inner (frame) raster
 * @param {number} p.PW @param {number} p.PH        padded raster (frame + outpaint border)
 * @param {number} p.bx @param {number} p.by        border in px
 * @param {number} p.f                              focal length, px at W×H
 * @param {number} p.invFar @param {number} p.invNear  1/z at d̂ = 0 and at d̂ = 1
 * @param {Float32Array} p.out0   W×H×4  (d̂, α, ·, ·)            layer 0
 * @param {Uint8Array|Uint8ClampedArray} p.rgbPad  PW×PH×4 sRGB  layer 0 colour
 * @param {Float32Array} p.out1   PW×PH×4 (r, g, b, d̂₁ | ≤NO_LAYER) layer 1, the full-res band
 * @param {Float32Array} [p.outB] PW×PH×4 same encoding: layer 1's backplate, emitted at half res
 * @param {number} [p.sigmaPx=0.65]  σ of a splat in its pixel's footprint
 * @param {boolean} [p.orient=true] surfels on the local tangent plane (see SURFEL SHAPE); false =
 *                                   frontoparallel disks with a slope-derived z-thickness
 * @param {number} [p.thin=0.15]     thickness (normal-axis σ) as a fraction of the in-plane σ
 * @param {number} [p.slopeGain=0.5] (orient:false) z-σ per metre of one-sided depth step
 * @param {number} [p.maxAniso=8]    cap on a depth step, in pixel footprints
 * @param {number} [p.minAlpha=0.02] layer-0 splats below this are skipped
 * @param {number} [p.pivotRegion=0.3] half-size (fraction) of the central box pivotZ is the median of
 */
export function emitLiftSplats(p) {
  const {
    W, H, PW, PH, bx, by, f, invFar, invNear, out0, rgbPad, out1, outB = null,
    sigmaPx = 0.65, thin = 0.15, slopeGain = 0.5, maxAniso = 8, maxAnisoEdge = maxAniso, minAlpha = 0.02, pivotRegion = 0.2, orient = true,
    emitLayers = 3, // DEV: bit 0 = layer 0, bit 1 = layer 1
  } = p;
  const cx = W / 2, cy = H / 2;
  const zOf = (d) => 1 / (invFar + d * (invNear - invFar));

  // ── depth fields ──
  const z0 = new Float32Array(W * H);
  for (let i = 0; i < W * H; i++) z0[i] = zOf(out0[4 * i]);
  const z1 = new Float32Array(PW * PH);
  let n1 = 0;
  for (let i = 0; i < PW * PH; i++) {
    const d = out1[4 * i + 3];
    if (d > NO_LAYER) { z1[i] = zOf(d); n1++; } else z1[i] = NaN;
  }
  let n0 = 0;
  if (emitLayers & 1) for (let i = 0; i < W * H; i++) if (out0[4 * i + 1] >= minAlpha) n0++;
  if (!(emitLayers & 2)) { n1 = 0; z1.fill(NaN); }

  // BACKPLATE: the hidden layer beyond the band, at half resolution — one splat per 2×2 cell that
  // holds any backplate texel, at the mean of those texels (depth, colour), twice the footprint.
  const CW = PW >> 1, CH = PH >> 1;
  let zB = null, cB = null, nB = 0;
  if (outB && emitLayers & 2) {
    zB = new Float32Array(CW * CH).fill(NaN);
    cB = new Float32Array(CW * CH * 3);
    for (let cv = 0; cv < CH; cv++)
      for (let cu = 0; cu < CW; cu++) {
        let n = 0, d = 0, r = 0, g = 0, b = 0;
        for (let j = 0; j < 2; j++)
          for (let k = 0; k < 2; k++) {
            const t = 4 * ((2 * cv + j) * PW + 2 * cu + k);
            if (outB[t + 3] > NO_LAYER) { n++; d += outB[t + 3]; r += outB[t]; g += outB[t + 1]; b += outB[t + 2]; }
          }
        if (!n) continue;
        const c = cv * CW + cu;
        zB[c] = zOf(d / n);
        cB[3 * c] = r / n; cB[3 * c + 1] = g / n; cB[3 * c + 2] = b / n;
        nB++;
      }
  }

  const count = n0 + n1 + nB;
  // Pad the comment so the body starts 4-byte aligned and can be written through a Float32Array
  // (every browser is little-endian; the header says so explicitly).
  let comment = 'generated by @displayxr/inline3d lift-gen';
  let header = new TextEncoder().encode(plyHeader(count, comment));
  while (header.length % 4) header = new TextEncoder().encode(plyHeader(count, (comment += ' ')));
  const buf = new ArrayBuffer(header.length + count * NP * 4);
  new Uint8Array(buf).set(header);
  const F = new Float32Array(buf, header.length);
  let o = 0;
  const min = [Infinity, Infinity, Infinity], max = [-Infinity, -Infinity, -Infinity];
  const put = (x, y, z, r, g, b, alpha, s0, s1, s2, qw, qx, qy, qz) => {
    F[o] = x; F[o + 1] = y; F[o + 2] = z;
    F[o + 3] = 0; F[o + 4] = 0; F[o + 5] = 0;
    F[o + 6] = (r - 0.5) / SH_C0; F[o + 7] = (g - 0.5) / SH_C0; F[o + 8] = (b - 0.5) / SH_C0;
    F[o + 9] = logit(Math.min(0.995, Math.max(0.005, alpha)));
    F[o + 10] = Math.log(s0); F[o + 11] = Math.log(s1); F[o + 12] = Math.log(s2);
    F[o + 13] = qw; F[o + 14] = qx; F[o + 15] = qy; F[o + 16] = qz;
    o += NP;
    if (x < min[0]) min[0] = x; if (x > max[0]) max[0] = x;
    if (y < min[1]) min[1] = y; if (y > max[1]) max[1] = y;
    if (z < min[2]) min[2] = z; if (z > max[2]) max[2] = z;
  };

  // SURFEL SHAPE. Each Gaussian is a disk on the local tangent plane of the depth surface: its
  // two in-plane axes are the 3D steps to the neighbouring pixels (∂P/∂u, ∂P/∂v), so a slanted
  // surface — a floor, a wall seen at an angle — is tiled edge-to-edge in 3D and stays closed
  // from any viewpoint, where frontoparallel disks would open into rows of gaps (moiré rings on
  // a floor). Each derivative is ONE-SIDED, taking the side with the smaller depth step, so a
  // depth DISCONTINUITY is never mistaken for a slant; the depth part of a step is capped at
  // maxAniso pixel footprints (a grazing floor is steeper than that, and an uncapped disk there
  // becomes a long streak). `orient: false` gives the simple frontoparallel disks (identity
  // rotation, z-thickness from the slope) for A/B.
  const q = new Float64Array(4);
  const tu = new Float64Array(3), tv = new Float64Array(3);
  /** The one-sided, capped depth step to the neighbour along `stride` (NaN/≤0 = no neighbour). */
  const tangent = (z, i, stride, hasPrev, hasNext, pix, aniso = maxAniso) => {
    const c = z[i];
    const zp = hasPrev ? z[i - stride] : NaN, zn = hasNext ? z[i + stride] : NaN;
    const a = zp > 0 ? c - zp : NaN;
    const b = zn > 0 ? zn - c : NaN;
    let dz = a !== a ? (b !== b ? 0 : b) : b !== b ? a : Math.abs(a) < Math.abs(b) ? a : b;
    const cap = aniso * pix;
    if (dz > cap) dz = cap; else if (dz < -cap) dz = -cap;
    return dz;
  };
  const emit = (x, y, z, dzu, dzv, pix, r, g, b, alpha) => {
    const s = sigmaPx * pix;
    if (!orient) {
      const sz = Math.min(maxAniso * s, Math.max(thin * s, slopeGain * Math.max(Math.abs(dzu), Math.abs(dzv))));
      put(x, y, z, r, g, b, alpha, s, s, sz, 1, 0, 0, 0);
      return;
    }
    // P(u,v) = ((u+.5−cx)·z/f, (v+.5−cy)·z/f, z) ⇒ ∂P/∂u = (z/f + x·dz/z, y·dz/z, dz)
    tu[0] = pix + (x * dzu) / z; tu[1] = (y * dzu) / z; tu[2] = dzu;
    tv[0] = (x * dzv) / z; tv[1] = pix + (y * dzv) / z; tv[2] = dzv;
    const lu = Math.sqrt(tu[0] * tu[0] + tu[1] * tu[1] + tu[2] * tu[2]);
    const e1x = tu[0] / lu, e1y = tu[1] / lu, e1z = tu[2] / lu;
    const dp = tv[0] * e1x + tv[1] * e1y + tv[2] * e1z;
    let e2x = tv[0] - dp * e1x, e2y = tv[1] - dp * e1y, e2z = tv[2] - dp * e1z;
    const lv = Math.sqrt(e2x * e2x + e2y * e2y + e2z * e2z);
    e2x /= lv; e2y /= lv; e2z /= lv;
    const e3x = e1y * e2z - e1z * e2y, e3y = e1z * e2x - e1x * e2z, e3z = e1x * e2y - e1y * e2x;
    matToQuat(e1x, e2x, e3x, e1y, e2y, e3y, e1z, e2z, e3z, q);
    const s1 = sigmaPx * lu, s2 = sigmaPx * lv;
    put(x, y, z, r, g, b, alpha, s1, s2, thin * Math.min(s1, s2), q[0], q[1], q[2], q[3]);
  };

  // ── layer 0: one Gaussian per frame pixel ──
  for (let v = 0; v < H; v++) {
    for (let u = 0; u < W; u++) {
      const i = v * W + u;
      const alpha = out0[4 * i + 1];
      if (alpha < minAlpha || !(emitLayers & 1)) continue;
      const z = z0[i];
      const pix = z / f;
      // out0 = (d̂, α, packed un-mixed RGB | −1, silhouette flag) — see passes/matte.glsl.js
      const sil = out0[4 * i + 3] > 0.5;
      const an = sil ? maxAnisoEdge : maxAniso;
      const dzu = tangent(z0, i, 1, u > 0, u < W - 1, pix, an);
      const dzv = tangent(z0, i, W, v > 0, v < H - 1, pix, an);
      const pk = out0[4 * i + 2];
      let r, g, b;
      if (sil && pk >= 0) {
        r = Math.floor(pk / 65536) / 255; g = (Math.floor(pk / 256) % 256) / 255; b = (pk % 256) / 255;
      } else {
        const pi = ((v + by) * PW + (u + bx)) * 4;
        r = rgbPad[pi] / 255; g = rgbPad[pi + 1] / 255; b = rgbPad[pi + 2] / 255;
      }
      emit(((u + 0.5 - cx) * z) / f, ((v + 0.5 - cy) * z) / f, z, dzu, dzv, pix, r, g, b, alpha);
    }
  }
  // ── layer 1: the hidden background, only where it exists ──
  for (let v = 0; v < PH; v++) {
    for (let u = 0; u < PW; u++) {
      const i = v * PW + u;
      const z = z1[i];
      if (!(z > 0)) continue;
      const pix = z / f;
      const dzu = tangent(z1, i, 1, u > 0, u < PW - 1, pix);
      const dzv = tangent(z1, i, PW, v > 0, v < PH - 1, pix);
      const uu = u - bx, vv = v - by;
      emit(((uu + 0.5 - cx) * z) / f, ((vv + 0.5 - cy) * z) / f, z, dzu, dzv, pix,
        clamp01(out1[4 * i]), clamp01(out1[4 * i + 1]), clamp01(out1[4 * i + 2]), 0.995);
    }
  }

  // ── layer 1, backplate part (half resolution) ──
  if (zB) {
    for (let cv = 0; cv < CH; cv++) {
      for (let cu = 0; cu < CW; cu++) {
        const c = cv * CW + cu;
        const z = zB[c];
        if (!(z > 0)) continue;
        const pix = (2 * z) / f;
        const dzu = tangent(zB, c, 1, cu > 0, cu < CW - 1, pix);
        const dzv = tangent(zB, c, CW, cv > 0, cv < CH - 1, pix);
        const uu = 2 * cu + 1 - bx, vv = 2 * cv + 1 - by; // cell centre, in frame pixels
        emit(((uu - cx) * z) / f, ((vv - cy) * z) / f, z, dzu, dzv, pix,
          clamp01(cB[3 * c]), clamp01(cB[3 * c + 1]), clamp01(cB[3 * c + 2]), 0.995);
      }
    }
  }

  // pivotZ: median layer-0 depth of the central box
  const r = pivotRegion;
  const cz = [];
  for (let v = Math.floor(H * (0.5 - r)); v < Math.ceil(H * (0.5 + r)); v++)
    for (let u = Math.floor(W * (0.5 - r)); u < Math.ceil(W * (0.5 + r)); u++) cz.push(z0[v * W + u]);
  cz.sort((a, b) => a - b);
  const pivotZ = cz.length ? cz[cz.length >> 1] : zOf(0.5);

  return { ply: buf, splatCount: count, layerCounts: [n0, n1 + nB], bandCount: n1, backplateCount: nB, bounds: { min, max }, pivotZ };
}

/** Rotation matrix (row-major m00..m22, columns = local axes in world) → unit quaternion w,x,y,z. */
export function matToQuat(m00, m01, m02, m10, m11, m12, m20, m21, m22, out) {
  const tr = m00 + m11 + m22;
  let w, x, y, z;
  if (tr > 0) {
    const S = Math.sqrt(tr + 1) * 2;
    w = 0.25 * S; x = (m21 - m12) / S; y = (m02 - m20) / S; z = (m10 - m01) / S;
  } else if (m00 > m11 && m00 > m22) {
    const S = Math.sqrt(1 + m00 - m11 - m22) * 2;
    w = (m21 - m12) / S; x = 0.25 * S; y = (m01 + m10) / S; z = (m02 + m20) / S;
  } else if (m11 > m22) {
    const S = Math.sqrt(1 + m11 - m00 - m22) * 2;
    w = (m02 - m20) / S; x = (m01 + m10) / S; y = 0.25 * S; z = (m12 + m21) / S;
  } else {
    const S = Math.sqrt(1 + m22 - m00 - m11) * 2;
    w = (m10 - m01) / S; x = (m02 + m20) / S; y = (m12 + m21) / S; z = 0.25 * S;
  }
  if (w < 0) { w = -w; x = -x; y = -y; z = -z; }
  const n = Math.sqrt(w * w + x * x + y * y + z * z);
  out[0] = w / n; out[1] = x / n; out[2] = y / n; out[3] = z / n;
  return out;
}

function clamp01(x) {
  return x < 0 ? 0 : x > 1 ? 1 : x;
}

/**
 * Parse a binary little-endian PLY whose vertex properties are all float32 (what this writer
 * emits). For tests and diagnostics — not a general PLY reader.
 * @param {ArrayBuffer} buf
 * @returns {{count:number, props:string[], data:Float32Array, headerBytes:number}}
 */
export function parsePly(buf) {
  const u8 = new Uint8Array(buf);
  const endTag = 'end_header\n';
  let end = -1;
  const lim = Math.min(u8.length, 64 * 1024);
  const text = new TextDecoder().decode(u8.subarray(0, lim));
  const at = text.indexOf(endTag);
  if (at < 0) throw new Error('parsePly: no end_header');
  end = new TextEncoder().encode(text.slice(0, at + endTag.length)).length;
  const lines = text.slice(0, at).split('\n');
  if (lines[0] !== 'ply') throw new Error('parsePly: not a PLY');
  if (!lines.includes('format binary_little_endian 1.0')) throw new Error('parsePly: not binary LE');
  let count = 0;
  const props = [];
  for (const l of lines) {
    const t = l.split(/\s+/);
    if (t[0] === 'element' && t[1] === 'vertex') count = +t[2];
    if (t[0] === 'property') {
      if (t[1] !== 'float') throw new Error(`parsePly: property ${t[2]} is ${t[1]}, only float is supported`);
      props.push(t[2]);
    }
  }
  const expect = end + count * props.length * 4;
  if (u8.length !== expect) throw new Error(`parsePly: size ${u8.length} != ${expect}`);
  const data = new Float32Array(count * props.length);
  const dv = new DataView(buf, end);
  for (let i = 0; i < data.length; i++) data[i] = dv.getFloat32(i * 4, true);
  return { count, props, data, headerBytes: end };
}

// ── Worker entry ──
// eslint-disable-next-line no-undef
if (typeof WorkerGlobalScope !== 'undefined' && typeof self !== 'undefined' && self instanceof WorkerGlobalScope) {
  self.onmessage = (e) => {
    try {
      const r = emitLiftSplats(e.data);
      self.postMessage({ ok: true, ...r }, [r.ply]);
    } catch (err) {
      self.postMessage({ ok: false, error: String((err && err.stack) || err) });
    }
  };
}
