// Keeps the agent-agnostic instructions and the Claude plugin in step with this package.
//
//   node tools/inline3d-tools/scripts/sync-agents.mjs           rewrite (run after editing a skill or bumping the version)
//   node tools/inline3d-tools/scripts/sync-agents.mjs --check   exit 1 if anything is out of date (CI + test/agents-sync.test.mjs)
//
// 1. Every `@displayxr/inline3d-tools@X.Y.Z` pin in the plugin's skills, command and README (and in
//    this package's README) equals this package's version (the plugin runs the package at exactly that version).
// 2. tools/inline3d-tools/AGENTS.md is generated from the plugin's three SKILL.md files: the same
//    checklist and workflow, with a preamble on how a non-Claude agent calls the tools.
// 3. plugins/displayxr-inline3d-codex/ (the OpenAI Codex plugin) is generated from the Claude plugin:
//    skills/, LICENSE and the icon are byte copies; .codex-plugin/plugin.json and .mcp.json are built
//    here (version = the Claude plugin's, MCP server = this package at PIN). Only its README.md is
//    hand-written. It is a separate folder so the Claude plugin stays free of MCP config (directory
//    rule for unverified orgs), and because Codex reads .codex-plugin/ before .claude-plugin/ and only
//    falls back to a root plugin.json when neither exists.
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const PKG_DIR = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = join(PKG_DIR, '..', '..');
const PLUGIN = join(REPO, 'plugins', 'displayxr-inline3d');
const CODEX = join(REPO, 'plugins', 'displayxr-inline3d-codex');
const VERSION = JSON.parse(readFileSync(join(PKG_DIR, 'package.json'), 'utf8')).version;
const PIN = `@displayxr/inline3d-tools@${VERSION}`;
const PIN_RE = /@displayxr\/inline3d-tools@\d+\.\d+\.\d+(?:-[\w.]+)?/g;
const SKILLS = [
  ['inline3d', 'Building on @displayxr/inline3d'],
  ['new-inline3d-page', 'Scaffold an inline-3D page'],
  ['inline3d-assets', 'Assets for inline-3D pages'],
];

function walk(dir, out = []) {
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(md|json)$/.test(n)) out.push(p);
  }
  return out;
}

// Claude-plugin wording -> wording that works for any agent reading one file.
function adapt(md) {
  return md
    .replace(/the\s+`new-inline3d-page`\s+skill/g, 'the "Scaffold an inline-3D page" section below')
    .replace(/the\s+`inline3d-assets`\s+skill/g, 'the "Assets for inline-3D pages" section below')
    .replace(/this skill does not copy them/g, 'this file does not copy them')
    .replace(/\(`inline3d`\s+skill §7\)/g, '("Building on @displayxr/inline3d" §7)')
    .replace(/the `inline3d` skill §1 table/g, 'the "Building on @displayxr/inline3d" §1 table')
    .replace(/the user approves the command/g, 'the user may be asked to approve the command');
}

function body(name) {
  const src = readFileSync(join(PLUGIN, 'skills', name, 'SKILL.md'), 'utf8');
  const m = src.match(/^---\n[\s\S]*?\n---\n+/);
  const text = m ? src.slice(m[0].length) : src;
  // Demote headings one level so the file has a single H1.
  return adapt(text.replace(/^(#{1,5}) /gm, '#$1 ').trim());
}

export function buildAgents() {
  const T = `npx -y ${PIN}`;
  const parts = [`<!-- GENERATED by tools/inline3d-tools/scripts/sync-agents.mjs from plugins/displayxr-inline3d/skills/*/SKILL.md. Do not edit by hand: edit the skills and re-run the script. -->

# Agent instructions: glasses-free 3D web pages with @displayxr/inline3d

For any coding agent (OpenAI Codex, Cursor, Claude Code without the plugin, others). Copy this file
into a project as \`AGENTS.md\` (or point your agent at it) when the project builds pages on
[\`@displayxr/inline3d\`](https://www.npmjs.com/package/@displayxr/inline3d).

## How to call the tools

The tools are the npm package \`@displayxr/inline3d-tools\`, pinned to an exact version. **In a
sandboxed agent, prefer the MCP server** (below): MCP servers run outside the sandbox, while a shell
\`check\` starts a local file server and headless Chrome, which OpenAI Codex's default sandbox blocks
(\`listen EPERM 127.0.0.1\`), so there it needs the user to approve running the command outside the
sandbox. Otherwise run them as shell commands:

\`\`\`sh
${T} check <url | dir | page.html> [--root <project>] [--max-texture 4096]
${T} assets <file.glb> [--target tablet|desktop]
${T} assets prep <in> <out.glb> [--metres 0.01] [--decimate 0.5]
${T} scaffold <esm|vite> <target-dir> --title "<page title>"
${T} gen providers | gen run <adapter> ... --confirm-paid | gen provenance --file ...
\`\`\`

or, with the MCP server configured (\`inline3d-tools mcp\`; config snippets for Codex, Cursor and
Claude Code in this package's README), call its tools with the same
semantics: \`check\`, \`asset_check\`, \`scaffold\`, \`gen_providers\`, \`gen_run\` (paid: pass
\`confirm_paid: true\` only after the user approved that one call and its cost),
\`gen_provenance\`, \`authoring_guide\` (returns this file). Relative paths resolve against the
server's working directory.

Needs Node ≥ 18; \`check\` also needs a local Chrome or Chromium (\`CHROME=/path/to/chrome\`).
Generator keys come only from the environment (\`MESHY_API_KEY\`, \`TRIPO_API_KEY\`,
\`OPENAI_API_KEY\`); never ask for, print, log or write one.`];
  for (const [name, title] of SKILLS) {
    const b = body(name);
    if (!b.startsWith(`## ${title}`)) throw new Error(`${name}/SKILL.md must start with "# ${title}"`);
    parts.push(b);
  }
  return parts.join('\n\n') + '\n';
}

function allFiles(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) allFiles(p, out); else out.push(p);
  }
  return out;
}

// Generated files of the Codex plugin: path relative to CODEX -> Buffer.
export function buildCodexPlugin() {
  const files = new Map();
  for (const f of allFiles(join(PLUGIN, 'skills'))) files.set(join('skills', relative(join(PLUGIN, 'skills'), f)), readFileSync(f));
  files.set('LICENSE', readFileSync(join(PLUGIN, 'LICENSE')));
  files.set(join('assets', 'icon.png'), readFileSync(join(PLUGIN, '.claude-plugin', 'icon.png')));
  const claude = JSON.parse(readFileSync(join(PLUGIN, '.claude-plugin', 'plugin.json'), 'utf8'));
  const manifest = {
    name: 'displayxr-inline3d-codex',
    version: claude.version,
    description: claude.description,
    author: claude.author,
    homepage: 'https://github.com/DisplayXR/displayxr-web/tree/main/plugins/displayxr-inline3d-codex',
    repository: claude.repository,
    license: claude.license,
    keywords: claude.keywords,
    interface: {
      displayName: 'DisplayXR Inline 3D',
      shortDescription: 'Build and check 3D web pages for spatial displays',
      longDescription: 'Skills and a local MCP server for pages built on @displayxr/inline3d: pick the entry point and view rig, scaffold a page from a known-good template, prepare and budget-check 3D assets, and check the page headlessly (two real eye views plus a plain 2D run) before calling it done.',
      developerName: 'DisplayXR',
      category: 'Developer Tools',
      capabilities: ['Read', 'Write'],
      websiteURL: 'https://displayxr.org/',
      privacyPolicyURL: claude.privacyPolicyUrl,
      supportURL: claude.supportUrl,
      defaultPrompt: [
        'Make a 3D web page for a spatial display that shows my model',
        'Check this inline-3D page and fix what fails',
      ],
      composerIcon: './assets/icon.png',
      logo: './assets/icon.png',
    },
    mcpServers: './.mcp.json',
  };
  const mcp = {
    mcpServers: {
      'inline3d-tools': {
        command: 'npx',
        args: ['-y', PIN, 'mcp'],
        startup_timeout_sec: 60,
        tool_timeout_sec: 180,
      },
    },
  };
  files.set(join('.codex-plugin', 'plugin.json'), Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`));
  files.set('.mcp.json', Buffer.from(`${JSON.stringify(mcp, null, 2)}\n`));
  return files;
}

function syncCodex(check, stale) {
  const want = buildCodexPlugin();
  for (const [rel, buf] of want) {
    const f = join(CODEX, rel);
    let have = null;
    try { have = readFileSync(f); } catch { /* missing */ }
    if (!have || !have.equals(buf)) {
      stale.push(`${relative(REPO, f)}: out of date with the Claude plugin`);
      if (!check) { mkdirSync(dirname(f), { recursive: true }); writeFileSync(f, buf); }
    }
  }
  // Nothing in the Codex plugin but the generated files and its own README.
  for (const f of allFiles(CODEX)) {
    const rel = relative(CODEX, f);
    if (rel === 'README.md' || want.has(rel)) continue;
    stale.push(`${relative(REPO, f)}: not generated from the Claude plugin`);
    if (!check) rmSync(f);
  }
}

export function sync({ check = false } = {}) {
  const stale = [];
  // Pins first: the Codex plugin copies the Claude plugin's skills, so it must see them rewritten.
  for (const f of [...walk(PLUGIN), ...(existsSync(join(CODEX, 'README.md')) ? [join(CODEX, 'README.md')] : []), join(PKG_DIR, 'README.md')]) {
    const s = readFileSync(f, 'utf8');
    const t = s.replace(PIN_RE, PIN);
    if (t !== s) { stale.push(`${relative(REPO, f)}: pin is not ${PIN}`); if (!check) writeFileSync(f, t); }
  }
  syncCodex(check, stale);
  const agentsPath = join(PKG_DIR, 'AGENTS.md');
  const want = buildAgents();
  let have = '';
  try { have = readFileSync(agentsPath, 'utf8'); } catch { /* missing */ }
  if (have !== want) { stale.push(`${relative(REPO, agentsPath)}: out of date with the skills`); if (!check) writeFileSync(agentsPath, want); }
  return stale;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  const stale = sync({ check });
  if (check && stale.length) {
    console.error(`out of date (run: node tools/inline3d-tools/scripts/sync-agents.mjs):\n${stale.map((s) => `  ${s}`).join('\n')}`);
    process.exit(1);
  }
  console.log(stale.length ? `updated:\n${stale.map((s) => `  ${s}`).join('\n')}` : 'in sync');
}
